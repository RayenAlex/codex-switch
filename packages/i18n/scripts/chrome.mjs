import fs from 'node:fs';
import path from 'node:path';

const escape = value => value.replace(/[&<>"']/g, character => `&#${character.charCodeAt(0)};`);

/** Keep the extension's offline defaults and initial HTML in sync with its default catalog. */
export function generateChromeResources(root, config, generated) {
  const messages = JSON.parse(fs.readFileSync(path.join(root, config.source), 'utf8'));
  const text = key => {
    if (!messages[key]) throw new Error(`Missing Chrome message: ${key}`);
    return escape(messages[key].message);
  };
  const defaults = Object.fromEntries(Object.entries(messages).map(([key, entry]) => [key, entry.message]));
  generated.set(`../../${config.module}`, '// Generated by npm run generate:i18n. Do not edit.\n'
    + `export default ${JSON.stringify(defaults, null, 2)};\n`);
  for (const page of config.pages) {
    let html = fs.readFileSync(path.join(root, '../../', page), 'utf8').replace(/\r\n/g, '\n');
    html = html.replace(/<([\w-]+)\b([^>]*\bdata-i18n="([^"]+)"[^>]*)>[^<]*<\/\1>/g,
      (_, tag, attributes, key) => `<${tag}${attributes}>${text(key)}</${tag}>`);
    html = html.replace(/<[\w-]+\b[^>]*>/g, tag => {
      for (const [, attribute, key] of tag.matchAll(/data-i18n-(title|aria-label|placeholder)="([^"]+)"/g)) {
        const pattern = new RegExp(`(\\s${attribute}=")[^"]*(")`);
        if (!pattern.test(tag)) throw new Error(`Missing localized attribute: ${page}/${attribute}`);
        tag = tag.replace(pattern, (_, prefix, suffix) => `${prefix}${text(key)}${suffix}`);
      }
      return tag;
    });
    generated.set(`../../${page}`, html);
  }
}
