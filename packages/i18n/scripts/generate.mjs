import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { messageParams, validateCatalog } from './validation.mjs';
import { generatePlatformResources } from './platform.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const metadata = read('languages.json');
const catalogs = read('catalogs.json');
const errors = [];
const generated = new Map();
const banner = '// Generated by npm run generate:i18n. Do not edit.\n';
const json = data => JSON.stringify(data, null, 2);
const ids = metadata.languages.map(language => language.id);

function validateRegistry() {
  if (new Set(ids).size !== ids.length) errors.push('Duplicate language ID');
  const aliases = new Set();
  for (const language of metadata.languages) {
    if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(language.id)) errors.push(`Invalid language ID: ${language.id}`);
    if (!['ltr', 'rtl'].includes(language.direction)) errors.push(`Invalid direction: ${language.id}`);
    for (const alias of [language.id, ...language.aliases]) {
      const normalized = alias.toLowerCase();
      if (aliases.has(normalized)) errors.push(`Duplicate language alias: ${alias}`);
      aliases.add(normalized);
    }
    const visited = new Set([language.id]);
    let fallback = language.fallback;
    while (fallback) {
      if (!ids.includes(fallback) || visited.has(fallback)) { errors.push(`Invalid fallback: ${language.id}`); break; }
      visited.add(fallback);
      fallback = metadata.languages.find(item => item.id === fallback).fallback;
    }
  }
  for (const [app, enabled] of Object.entries(metadata.applications)) {
    if (!enabled.length || enabled.some(id => !ids.includes(id))) errors.push(`Invalid application languages: ${app}`);
    if (new Set(enabled).size !== enabled.length) errors.push(`Duplicate application language: ${app}`);
  }
}

function readCatalog(module, language) {
  const directory = `src/catalogs/${module}/${language}`;
  const absolute = path.join(root, directory);
  const files = fs.existsSync(absolute) ? fs.readdirSync(absolute).filter(name => name.endsWith('.json')).sort() : [];
  const messages = {};
  for (const file of files) {
    const entries = read(`${directory}/${file}`);
    for (const key of Object.keys(entries)) if (Object.hasOwn(messages, key)) errors.push(`${directory}: duplicate ${key}`);
    Object.assign(messages, entries);
  }
  if (files.length) {
    const imports = files.map((file, index) => `import part${index} from './${file}';`);
    const merge = files.map((_, index) => `...part${index}`).join(', ');
    generated.set(`${directory}/index.ts`, `${banner}${imports.join('\n')}\nexport default { ${merge} };\n`);
  }
  return { messages, exists: files.length > 0 };
}

function generateCatalog(module, policy) {
  const locales = [...policy.released, ...policy.draft];
  if (new Set(locales).size !== locales.length || locales.some(id => !ids.includes(id))) {
    errors.push(`${module}: invalid release policy`);
    return {};
  }
  for (const app of policy.applications ?? []) {
    const enabled = metadata.applications[app];
    if (!enabled || enabled.some(id => !policy.released.includes(id))) {
      errors.push(`${module}: application ${app} enables an unreleased language`);
    }
  }
  const resources = Object.fromEntries(locales.map(id => [id, readCatalog(module, id)]));
  const base = resources[policy.base]?.messages;
  if (!base || !Object.keys(base).length) { errors.push(`${module}: missing base dictionary`); return {}; }
  for (const language of locales) {
    errors.push(...validateCatalog({ base, target: resources[language].messages, label: `${module}/${language}`,
      released: policy.released.includes(language), locale: metadata.languages.find(item => item.id === language).locale }));
  }
  const available = locales.filter(id => resources[id].exists);
  const imports = available.map(id => `import ${id} from './${id}';`).join('\n');
  generated.set(`src/catalogs/${module}/index.ts`, `${banner}${imports}\nexport const resources = { ${available.join(', ')} };\n`);
  return { base, available };
}

function generateTypes(messages) {
  const entries = Object.entries(messages).sort(([a], [b]) => a.localeCompare(b, 'en'));
  const chunks = [];
  for (let offset = 0; offset < entries.length; offset += 200) {
    const name = `MessageParams${offset / 200 + 1}`;
    chunks.push(name);
    const lines = entries.slice(offset, offset + 200).map(([key, message]) => {
      const params = messageParams(message).map(name =>
        `${JSON.stringify(name)}: ${typeof message !== 'string' && name === 'count' ? 'number' : 'string | number'}`);
      const type = params.length ? `{ ${params.join('; ')} }` : 'Record<string, never>';
      return `  ${JSON.stringify(key)}: ${type};`;
    });
    generated.set(`src/generated/${name}.ts`, `${banner}export interface ${name} {\n${lines.join('\n')}\n}\n`);
  }
  const imports = chunks.map(name => `import type { ${name} } from './${name}';`).join('\n');
  generated.set('src/generated/messages.ts', `${banner}${imports}\nexport interface MessageParams extends ${chunks.join(', ')} {}\n`
    + 'export type MessageKey = keyof MessageParams;\n');
}

function generateRust() {
  const nativeCodes = { zh: 0, en: 1, ru: 2, ja: 3 };
  const entries = metadata.applications.desktop.map(id => {
    const language = metadata.languages.find(item => item.id === id);
    const code = nativeCodes[language.nativeText];
    if (code === undefined) errors.push(`Missing Rust native resources for ${id}`);
    return `(${JSON.stringify(id)}, ${code})`;
  });
  const declaration = 'pub(super) const SUPPORTED_LANGUAGES: &[(&str, u8)] = &';
  const singleLine = `${declaration}[${entries.join(', ')}];`;
  const table = singleLine.length <= 100 ? singleLine : `${declaration}[\n${entries.map(row => `    ${row},`).join('\n')}\n];`;
  const content = '// Generated from packages/i18n/languages.json. Do not edit.\n'
    + `${table}\n`;
  generated.set('../../apps/desktop/src-tauri/src/storage/supported_languages.rs', content);
}

validateRegistry();
generated.set('src/generated/languages.ts', `${banner}export const languages = ${json(metadata.languages)} as const;\n`
  + `export const applications = ${json(metadata.applications)} as const;\n`);
const messages = {};
const loaders = [];
for (const [module, policy] of Object.entries(catalogs)) {
  const { base = {}, available = [] } = generateCatalog(module, policy);
  for (const key of Object.keys(base)) if (Object.hasOwn(messages, key)) errors.push(`Duplicate semantic key: ${key}`);
  Object.assign(messages, base);
  for (const id of available) loaders.push(`  '${module}/${id}': () => import('./${module}/${id}').then(module => module.default),`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
generateTypes(messages);
generateRust();
generatePlatformResources(root, generated);
generated.set('src/catalogs/loader.ts', `${banner}import type { Messages, ResourceLoader } from '../messages';\n`
  + `const loaders: Record<string, () => Promise<Messages>> = {\n${loaders.join('\n')}\n};\n`
  + 'export const loadResource: ResourceLoader = async (language, module) => loaders[`${module}/${language}`]?.();\n');

if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
for (const [file, content] of generated) {
  const absolute = path.join(root, file);
  const actual = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n') : undefined;
  if (actual === content) continue;
  if (check) { errors.push(`Outdated generated file: ${file}`); continue; }
  fs.mkdirSync(path.dirname(absolute), { recursive: true });
  fs.writeFileSync(absolute, content);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
console.log(`i18n: verified ${ids.length} languages, ${Object.keys(catalogs).length} modules and ${Object.keys(messages).length} keys`);
