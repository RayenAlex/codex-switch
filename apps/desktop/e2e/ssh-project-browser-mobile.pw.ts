import { expect, test } from '@playwright/test';
import { sshEditorFixture } from './ssh-editor-fixture';
import { longPress } from './project-browser-touch';

test.use({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, actionTimeout: 15_000 });

test('mobile web SSH uses the file tree, tabs, touch menus and retained drafts', async ({ page }, info) => {
  test.setTimeout(120_000);
  const fixture = await sshEditorFixture(page);
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ contentType: 'text/css', body: '' }));
  await page.addInitScript(() => localStorage.setItem('codex-switch.project-browser.auto-save', '0'));
  await page.goto('/e2e/ssh-harness.html?mode=web&cloud=1');
  expect(await page.evaluate(() => innerWidth)).toBe(390);
  await page.getByRole('button', { name: '打开远程终端', exact: true }).click();
  await page.getByRole('button', { name: '终端连接选项' }).click();
  await page.getByRole('menuitem', { name: 'Editor server', exact: true }).click();
  await page.getByRole('button', { name: '远程文件浏览', exact: true }).click();
  const row = (name: string) => page.getByRole('treeitem', { name, exact: true });
  await expect(row('hello.txt')).toBeVisible();
  await row('中文目录').click();
  await expect(row('nested.txt')).toBeVisible();
  await page.getByRole('searchbox', { name: '搜索文件或文件夹' }).fill('nested');
  await expect(row('nested.txt')).toContainText('中文目录/nested.txt');
  await page.getByRole('button', { name: '清空搜索' }).click();
  await longPress(page, row('hello.txt'));
  await expect(page.getByRole('menuitem', { name: '重命名', exact: true })).toBeVisible();
  await expect(page.getByRole('menuitem', { name: '复制', exact: true })).toBeDisabled();
  await page.screenshot({ path: info.outputPath('ssh-mobile-menu.png'), animations: 'disabled' });
  await page.keyboard.press('Escape');
  await row('script.ts').click();
  const editor = page.getByRole('textbox', { name: '文件内容', exact: true });
  await editor.fill('const mobile = "草稿";\n');
  await page.getByRole('button', { name: '返回文件列表', exact: true }).click();
  await expect(row('script.ts')).toBeVisible();
  await row('hello.txt').click();
  await page.getByRole('tab', { name: 'script.ts', exact: true }).click();
  await expect(editor).toContainText('草稿');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  await expect(page.locator('.pf-status:visible')).toContainText('已保存');
  expect(fixture.files.get('/script.ts')!.toString()).toBe('\ufeffconst mobile = "草稿";\r\n');
  await editor.fill('keep this mobile draft');
  await page.getByRole('button', { name: '关闭文件 script.ts', exact: true }).click();
  const confirm = page.getByRole('alertdialog');
  await expect(confirm).toBeVisible();
  expect((await confirm.boundingBox())!.width).toBeLessThanOrEqual(400);
  await page.screenshot({ path: info.outputPath('ssh-mobile-confirm.png'), animations: 'disabled' });
  await confirm.getByRole('button', { name: '取消', exact: true }).click();
  await expect(editor).toContainText('keep this mobile draft');
  await page.getByRole('button', { name: '返回终端', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await page.getByRole('button', { name: '远程文件浏览', exact: true }).click();
  await expect(editor).toContainText('keep this mobile draft');
  await expect(page.getByRole('button', { name: '返回终端', exact: true })).toBeInViewport();
  await expect(editor).toBeInViewport();
  expect((await page.locator('.ssh-files-drawer .pf-browser').boundingBox())!.height).toBeGreaterThan(700);
  await page.screenshot({ path: info.outputPath('ssh-mobile-editor.png'), animations: 'disabled' });
  await page.setViewportSize({ width: 844, height: 390 });
  await expect.poll(() => page.evaluate(() => innerWidth)).toBe(844);
  await expect.poll(() => page.evaluate(() => visualViewport?.scale)).toBe(1);
  await expect(page.getByRole('button', { name: '返回终端', exact: true })).toBeInViewport();
  await expect(editor).toBeInViewport();
  await page.screenshot({ path: info.outputPath('ssh-mobile-landscape.png'), animations: 'disabled' });
});
